import { test, expect } from './support/isolated-test.mjs';
import { revealVirginPlanet, queryIsolatedSql, runIsolatedSql } from './support/game-fixtures.mjs';

test('07-01 : contexte et retour d’une commande native', async ({page}, info) => {
  test.setTimeout(120000);
  const id=crypto.randomUUID().slice(0,8);
  const email='board0701-'+id+'@example.test';
  const password=crypto.randomUUID()+'aA1!';
  const project=process.env.BROWSER_ROUTER;
  const fixed={width:1920,height:1080};
  const mobile={width:390,height:844};
  const top=page.locator('.topbar');
  const universe=top.locator('.universe-context');
  const strip=page.locator('[data-live-region="resources"]');
  const chooser=page.locator('#sidebar-colony');
  const nav=page.getByRole('navigation',{name:'Navigation mobile',exact:true});
  const visibleMetal=() => strip.locator('[data-slug="metal"][data-resource-strip-target="compactStock"]:visible,[data-resource-slug="metal"] [data-resource-target="stock"]:visible').first();
  const shot=async (key,viewport) => {
    await page.setViewportSize(viewport);
    await expect(top).toBeVisible();
    await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(viewport.width);
    await page.screenshot({path:info.outputPath('0701-'+key+'-'+viewport.width+'.png'),animations:'disabled',scale:'css'});
  };
  await page.setViewportSize(fixed);
  await page.goto('/inscription');
  await page.getByLabel('Adresse email').fill(email);
  await page.getByLabel('Nom de commandant').fill('Navigation-'+id);
  await page.getByLabel('Mot de passe (12 caractères minimum)',{exact:true}).fill(password);
  await page.getByLabel('Confirmer le mot de passe').fill(password);
  await page.getByRole('button',{name:'Créer mon compte'}).click();
  await page.getByLabel('Adresse email').fill(email);
  await page.getByLabel('Mot de passe',{exact:true}).fill(password);
  await page.getByRole('button',{name:/Connexion/}).click();
  const chooseUniverse = name => page.locator('.universe-card').filter({has:page.getByRole('heading',{name})}).getByRole('button');
  await chooseUniverse(/Omega/).click();
  await expect(page).toHaveURL(/planetes\/\d+$/);
  const alpha = Number(new URL(page.url()).pathname.split('/').at(-1));
  expect(Number.isSafeInteger(alpha) && alpha > 0).toBe(true);
  const {id: beta}=await revealVirginPlanet(project,email);
  expect(Number.isSafeInteger(beta) && beta > 0 && beta!==alpha).toBe(true);
  const owned = '(SELECT owner FROM (SELECT owner_id AS owner FROM planet WHERE id='+alpha+') origin)';
  runIsolatedSql(project,"UPDATE planet SET name='Horizon témoin' WHERE id="+alpha+"; UPDATE planet SET owner_id="+owned+", name='Callisto témoin', acquired_at=UTC_TIMESTAMP() WHERE id="+beta);
  await page.reload();
  await expect(universe).toContainText(/Omega/i);
  await expect(strip).toHaveAttribute('aria-label','Ressources de Horizon témoin');
  await expect(chooser.locator('option')).toHaveCount(2);
  await chooser.focus();
  await shot('omega-horizon-selecteur',fixed);
  await chooser.selectOption(String(beta));
  await expect(page).toHaveURL(url=>url.pathname==='/planetes/'+beta);
  await expect(strip).toHaveAttribute('aria-label','Ressources de Callisto témoin');
  await expect(chooser).toHaveValue(String(beta));
  await shot('omega-callisto-actif',fixed);
  await page.setViewportSize(mobile);
  await nav.getByRole('button',{name:'Plus',exact:true}).click();
  await expect(chooser).toBeVisible();
  await chooser.focus();
  await shot('omega-callisto-selecteur',mobile);
  await chooser.selectOption(String(alpha));
  await expect(page).toHaveURL(url=>url.pathname==='/planetes/'+alpha);
  await expect(strip).toHaveAttribute('aria-label','Ressources de Horizon témoin');
  await shot('omega-horizon-actif',mobile);
  await universe.click();
  await expect(page).toHaveURL(/\/univers$/);
  await expect(chooseUniverse(/Turbo/)).toBeVisible();
  await shot('univers-choix',mobile);
  await shot('univers-choix',fixed);
  await chooseUniverse(/Turbo/).click();
  await expect(universe).toContainText(/Turbo/i);
  await expect(strip).not.toHaveAttribute('aria-label','Ressources de Horizon témoin');
  await shot('turbo-actif',fixed);
  await shot('turbo-actif',mobile);
  await universe.click();
  await chooseUniverse(/Omega/).click();
  await expect(universe).toContainText(/Omega/i);
  await expect(strip).toHaveAttribute('aria-label','Ressources de Horizon témoin');
  await page.setViewportSize(fixed);
  await page.getByRole('navigation',{name:'Navigation principale',exact:true}).getByRole('link',{name:'Bâtiments',exact:true}).click();
  const mine=page.locator('#item-mine_metal-basic');
  const order=mine.getByRole('button',{name:'Améliorer au niveau 1',exact:true});
  await expect(order).toBeEnabled();
  const price=()=>Number(queryIsolatedSql(project,"SELECT FLOOR(current_stock) FROM planet_resource WHERE planet_id="+alpha+" AND resource_type='metal'"));
  const entries=()=>Number(queryIsolatedSql(project,"SELECT COUNT(*) FROM queue_item WHERE planet_id="+alpha+" AND item_slug='mine_metal'"));
  const costBefore=price();
  const barBefore=await visibleMetal().getAttribute('title');
  expect(costBefore).toBeGreaterThan(0);
  expect(entries()).toBe(0);
  const [response]=await Promise.all([
    page.waitForResponse(r=>new URL(r.url()).pathname==='/planetes/'+alpha+'/construire' && r.request().method()==='POST'),
    order.click(),
  ]);
  await page.setViewportSize(mobile);
  expect(response.status()).toBe(302);
  await expect(page.getByText('Commande enregistrée dans la file.',{exact:true})).toBeVisible();
  await expect.poll(entries).toBe(1);
  expect(price()).toBeLessThan(costBefore);
  const result=page.locator('[data-queue-type="building"]');
  await expect(result).toHaveAttribute('data-queue-occupied','true');
  await expect(result).toContainText('Mine à ciel ouvert');
  await expect(visibleMetal()).not.toHaveAttribute('title',barBefore);
  await expect(strip).toHaveAttribute('aria-label','Ressources de Horizon témoin');
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await shot('commande-confirmee',mobile);
  await shot('commande-confirmee',fixed);
});
