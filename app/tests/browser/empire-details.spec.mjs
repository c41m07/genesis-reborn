import { test, expect } from './support/isolated-test.mjs';
import AxeBuilder from '@axe-core/playwright';
import { runIsolatedSql, queryIsolatedSql } from './support/game-fixtures.mjs';

test.use({ hasTouch: true });

test('Les détails des colonies sont accessibles au survol, au clavier et au toucher', async ({ page }, testInfo) => {
  test.setTimeout(120000);
  const id = crypto.randomUUID().slice(0, 8);
  const email = 'details-' + id + '@example.test';
  const password = 'Browser-test-2026!';
  await page.goto('/inscription');
  await page.getByLabel('Adresse email').fill(email);
  await page.getByLabel('Nom de commandant').fill('Details-' + id);
  await page.getByLabel('Mot de passe (12 caractères minimum)', { exact: true }).fill(password);
  await page.getByLabel('Confirmer le mot de passe').fill(password);
  await page.getByRole('button', { name: 'Créer mon compte' }).click();
  await expect(page).toHaveURL(/connexion/);
  await page.getByLabel('Adresse email').fill(email);
  await page.getByLabel('Mot de passe', { exact: true }).fill(password);
  await page.getByRole('button', { name: /Connexion/ }).click();
  await page.locator('article.universe-card').filter({ has: page.getByRole('heading', { name: /Turbo/ }) }).getByRole('button').click();
  await expect(page).toHaveURL(/planetes\/\d+$/);
  const project=process.env.BROWSER_ROUTER;
  const planetId=Number(new URL(page.url()).pathname.split('/').pop());
  const memberId=Number(queryIsolatedSql(project,`SELECT owner_id FROM planet WHERE id=${planetId}`));
  runIsolatedSql(project,`UPDATE planet SET name='Oreaiel' WHERE id=${planetId}`);
  runIsolatedSql(project,`INSERT INTO fleet (player_universe_id,home_planet_id,status,mission,speed_ratio,cargo,reserved_fuel,orbit_fuel,orbit_duration_seconds,travel_seconds,dispatch_token) SELECT ${memberId},${planetId},'idle','transport',1,'{}',0,0,0,0,'' WHERE NOT EXISTS (SELECT 1 FROM fleet WHERE home_planet_id=${planetId} AND status='idle')`);
  runIsolatedSql(project,`INSERT INTO fleet_ship (fleet_id,slug,tier,quantity) SELECT id,'transport','basic',3 FROM fleet WHERE home_planet_id=${planetId} AND status='idle' ON DUPLICATE KEY UPDATE quantity=3`);
  runIsolatedSql(project,`INSERT INTO fleet (player_universe_id,home_planet_id,destination_system_id,status,mission,speed_ratio,cargo,reserved_fuel,orbit_fuel,orbit_duration_seconds,departure_at,arrival_at,travel_seconds,dispatch_token) SELECT ${memberId},id,solar_system_id,'traveling','explore',1,'{"metal":120}',0,0,0,UTC_TIMESTAMP(),DATE_ADD(UTC_TIMESTAMP(),INTERVAL 1 HOUR),3600,UUID() FROM planet WHERE id=${planetId}`);
  const fleetId=Number(queryIsolatedSql(project,`SELECT MAX(id) FROM fleet WHERE player_universe_id=${memberId}`));
  runIsolatedSql(project,`INSERT INTO fleet_ship(fleet_id,slug,tier,quantity) VALUES(${fleetId},'transport','basic',2)`);
  for(const route of ['/planetes', '/planetes/'+planetId]) {
    await page.goto(route);
    const card=route==='/planetes'?page.locator('.planet-index-card').first():page.locator('.dashboard-colony').first();
    const trigger=card.getByRole('button',{name:/Oreaiel — Vaisseaux et ressources/});
    const panel=card.locator('.empire-details');
    await expect(panel).toBeHidden();
    const before=await card.boundingBox();
    await trigger.hover();
    await expect(panel).toBeVisible();
    expect((await card.boundingBox()).height).toBe(before.height);
    await expect(panel).toContainText('Stocks de ressources');
    await expect(panel).toContainText('Cargo de ligne');
    await expect(panel.getByRole('button',{name:/Fermer/})).toHaveCount(0);
    await panel.hover();
    await expect(panel).toBeVisible();
    await page.mouse.move(0,0);
    await expect(panel).toBeHidden();
    await trigger.click();
    await expect(panel).toBeVisible();
    await page.mouse.move(0,0);
    await expect(panel).toBeHidden();
    await page.getByRole('link',{name:'Aller au contenu',exact:true}).focus();
    await page.keyboard.press('Tab');
    await trigger.focus();
    await expect(panel).toBeVisible();
    expect(await trigger.evaluate(el=>el.matches(':focus-visible'))).toBe(true);
    await page.keyboard.press('Escape');
    await expect(panel).toBeHidden();
    await expect(trigger).toBeFocused();
    await page.keyboard.press('Space');
    await expect(panel).toBeVisible();
    expect((await new AxeBuilder({page}).include('.empire-details:popover-open').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([]);
    await page.getByRole('link',{name:'Aller au contenu',exact:true}).focus();
    await expect(panel).toBeHidden();
    await page.setViewportSize({width:390,height:844});
    await trigger.tap();
    await expect(panel).toBeVisible();
    await expect(panel).toContainText('Vaisseaux présents');
    expect((await trigger.boundingBox()).height).toBeGreaterThanOrEqual(44);
    const bounds=await panel.boundingBox();
    expect(bounds.x).toBeGreaterThanOrEqual(0);
    expect(bounds.x+bounds.width).toBeLessThanOrEqual(390);
    await page.screenshot({path:testInfo.outputPath(route==='/planetes'?'planet-popover-mobile.png':'overview-popover-mobile.png'),fullPage:false,animations:'disabled'});
    await page.touchscreen.tap(2,2);
    await expect(panel).toBeHidden();
  }
  const fleet=page.locator('[data-active-fleet="'+fleetId+'"]');
  const panel=fleet.locator('.empire-details');
  await fleet.locator('.operation-heading').hover();
  await expect(panel).toBeVisible();
  await expect(panel).toContainText('Fret transporté');
  await expect(panel).toContainText('120');
  await panel.hover();
  await expect(panel).toBeVisible();
  await page.mouse.move(0,0);
  await expect(panel).toBeHidden();
  await fleet.locator('.operation-heading').click();
  await expect(panel).toBeVisible();
  await page.mouse.move(0,0);
  await expect(panel).toBeHidden();
  await fleet.getByRole('button',{name:/Détails de la flotte/}).focus();
  await page.keyboard.press('Space');
  await expect(panel).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('fleet-popover-mobile.png'),fullPage:false,animations:'disabled'});
  await page.keyboard.press('Escape');
  await expect(panel).toBeHidden();
  await fleet.locator('.operation-heading').tap();
  await expect(panel).toBeVisible();
  await page.touchscreen.tap(2,2);
    await expect(panel).toBeHidden();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  runIsolatedSql(project,`UPDATE player SET preferences=JSON_SET(CASE WHEN JSON_TYPE(preferences)='OBJECT' THEN preferences ELSE JSON_OBJECT() END,'$.theme','light') WHERE email='${email}'`);
  await page.goto('/planetes');
  await page.getByRole('button',{name:/Oreaiel — Vaisseaux et ressources/}).tap();
  expect((await new AxeBuilder({page}).include('.empire-details:popover-open').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([]);
  await page.screenshot({path:testInfo.outputPath('planet-popover-light-mobile.png'),fullPage:false,animations:'disabled'});

});
